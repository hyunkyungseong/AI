    _직인_rowOff_from = 0
    _직인_col_to = 14       # O열 (N열 초과 — 583k+540k=1,123k > N열 1,094k)
    _직인_colOff_to = 29000    # 1,123,000 - 1,094,000 = 29,000 EMU
    _직인_row_to = 11       # Excel 12행 (0-based)
