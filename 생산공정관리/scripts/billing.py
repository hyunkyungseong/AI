    총수량_F = sum(용지자재별_F배율.values())
    _자재별_처리(행데이터, "출력자재비", 작업, rates, 용지자재별_F배율, 총수량_F, rates.get("용지제작단가", 0), 미등록수집)
    _자재별_처리(행데이터, "봉입자재비", 작업, rates, 봉투자재별, 봉투합, rates.get("봉투제작단가", 0), 미등록수집)
    _자재별_처리(행데이터, "삽지비", 작업, rates, 삽지자재별, 삽지, rates.get("삽지제작단가", 0), 미등록수집)


