def _절삭2(x):
    """소수점 셋째 자리부터 잘라 버림(반올림 아님) — 부동소수점 오차(예: 14.29*100=1428.9999...)
    로 한 자리 낮게 잘리는 걸 막기 위해 아주 작은 보정값을 더한 뒤 자른다. billingRules.절삭2()와 대칭."""
    return math.floor(x * 100 + 1e-9) / 100


def _평가_조건단일(row, 조건단일):
    필드값 = 조건단일["field"]
    비교값 = 조건단일.get("value", "")
    if 필드값 == "단가":
        # 단가는 숫자라 문자열 비교(str(14.0)=="14.0" 등)가 파이썬·JS 간 표현이 달라 어긋날 수 있음
        # → 숫자로 변환해 소수 2자리까지 절삭 비교(2026-07-28 조건식 "단가" 필드 추가)
        try:
            return _절삭2(float(row.get("단가", 0) or 0)) == _절삭2(float(비교값))
        except (TypeError, ValueError):
            return False
    필드값문자 = str(row.get(필드값, "") or "")
    비교값문자 = str(비교값 or "")
    if 조건단일.get("op") == "contains":
        return 비교값문자 in 필드값문자
    return 필드값문자 == 비교값문자


def _평가_and그룹(row, and그룹):
    조건들 = and그룹.get("and", [])
    if not 조건들:
        return False
    return all(_평가_조건단일(row, c) for c in 조건들)


def 평가_조건(row, 조건):
    """원본 행 하나(정렬행_원본목록()이 반환하는 dict)가 저장된 조건(OR-of-AND 트리)에 맞는지 판정.
    조건 = {"or": [{"and": [{"field","op","value"}, ...]}, ...]}
    조건["or"]가 빈 리스트면 무조건 True — 코드 구분 없이 전체를 합산하는 규칙을 표현하기 위함."""
    그룹들 = 조건.get("or", [])
    if not 그룹들:
        return True
    return any(_평가_and그룹(row, g) for g in 그룹들)


def 적용_규칙(원본행목록, 규칙목록):
    """원본행목록(정렬행_원본목록() 반환 형식)에 저장된 규칙들을 적용해 고객사 청구 명세서 초안을 만든다.
    규칙목록: [{"순서","최종청구품명","조건"}, ...] (순서는 오름차순으로 재정렬해서 검사)
    각 원본 행은 순서가 빠른 규칙부터 검사해 처음 매칭되는 규칙 한 곳에만 속한다(이중 청구 방지) —
    "전체 합산" 규칙(조건 없음)과 특정 코드 규칙을 같이 쓸 때는 전체 합산 규칙을 맨 뒤에 둬서
    "나머지 전부"를 받는 용도로 쓴다.
    반환: (규칙적용결과, 미분류) — 규칙적용결과는 규칙목록 순서 그대로
    [{"코드","표시품명","수량","단가"(단가가 갈리면 None),"금액"}, ...], 미분류는 어느 규칙에도
    안 걸린 원본행목록의 원소 그대로."""
    규칙정렬 = sorted(규칙목록, key=lambda r: r.get("순서", 0))
    매칭됨 = [False] * len(원본행목록)
    결과 = []
    for 규칙 in 규칙정렬:
        수량합 = 0.0
        금액합 = 0.0
        단가집합 = set()
        코드집합 = set()
        for i, row in enumerate(원본행목록):
            if 매칭됨[i]:
                continue
            if 평가_조건(row, 규칙["조건"]):
                매칭됨[i] = True
                수량합 += row["수량"]
                금액합 += row["금액"]
                단가집합.add(row["단가"])
                코드집합.add(row["코드"])
        결과.append({
            "코드": 코드집합.pop() if len(코드집합) == 1 else "",
            "표시품명": 규칙["최종청구품명"],
            "수량": 수량합,
            "단가": 단가집합.pop() if len(단가집합) == 1 else None,
            "금액": 금액합,
            "조": 규칙.get("조"),  # 조별 분할발급(2026-07-29) — 없으면 None(하위호환, 거래명세서 1건)
            # 구분표시(Excel B열)·규격(H열)·비고(N열) 조건식 입력(2026-08-11) — 규칙에 없으면
            # None(write_거래명세서_excel()이 구분표시는 발행일 자동값으로, 규격·비고는 빈 칸으로 처리)
            "구분표시": 규칙.get("구분표시"),
            "규격": 규칙.get("규격"),
            "비고": 규칙.get("비고"),
        })
    미분류 = [row for i, row in enumerate(원본행목록) if not 매칭됨[i]]
    return 결과, 미분류


def 병합_통합품목행(전체품목행):
    """조 2개 이상으로 나뉜 거래명세서의 맨 앞에 붙는 "통합 명세서" 시트용 — 모든 조의 품목행을
    "표시품명" 기준으로 병합한다(2026-08-12). 특정 조에만 있는 품목명도 그대로 포함(합집합), 같은
    표시품명이 여러 조에 걸쳐 있으면 수량·금액을 합산한다. 입력은 write_거래명세서_excel()이 받는
    품목행목록과 동일한 형식([{"코드","표시품명","수량","단가","금액","구분표시","규격","비고"}, ...])
    을 조 구분 없이 하나로 이어붙인 것.
    코드·단가는 적용_규칙()과 동일한 관례로 처리(전부 같으면 그 값, 다르면 코드는 빈 문자열·단가는
    None → write_거래명세서_excel()이 "—"로 표시). 구분표시·규격·비고는 조마다 다를 수 있는 텍스트라
    통합 시트에서는 항상 비운다(억지로 합치지 않음 — 구분표시가 비면 첫 행에 발행일이 자동 표기되는
    기존 동작이 통합 시트에도 그대로 적용된다)."""
    순서 = []
    집계 = {}
    for row in 전체품목행:
        키 = row["표시품명"]
        if 키 not in 집계:
            집계[키] = {"수량": 0.0, "금액": 0.0, "코드집합": set(), "단가집합": set()}
            순서.append(키)
        v = 집계[키]
        v["수량"] += row["수량"]
        v["금액"] += row["금액"]
        v["코드집합"].add(row.get("코드") or "")
        v["단가집합"].add(row.get("단가"))
    return [
        {
            "코드": 집계[키]["코드집합"].pop() if len(집계[키]["코드집합"]) == 1 else "",
            "표시품명": 키,
            "수량": 집계[키]["수량"],
            "단가": 집계[키]["단가집합"].pop() if len(집계[키]["단가집합"]) == 1 else None,
            "금액": 집계[키]["금액"],
            "구분표시": None,
            "규격": None,
            "비고": None,
        }
        for 키 in 순서
    ]


