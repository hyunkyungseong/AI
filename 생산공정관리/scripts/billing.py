    # 등록한 경우에만 보정하고, 미등록이면 지금까지와 완전히 동일하게 항상 장 수 그대로 청구한다
    # (자재단가 등록 자체가 없는 절대다수의 기존 거래처는 이 분기를 아예 타지 않아 회귀 없음).
