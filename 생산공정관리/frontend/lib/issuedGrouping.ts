import type { 발행행 } from "@/components/Dashboard";

// 레벨1(요약) 그리드 한 행 — 거래명세서번호 기준으로 합산한 것(2026-08-01, 거래명세서번호 단독
// 그룹핑으로 변경 — 그 전엔 거래명세서번호+업무명 기준이라, 거래명세서 1건이 업무명 여러 개에
// 걸치면(예: 조건식 병합으로 여러 업무명을 함께 요청) 같은 번호가 화면에 여러 줄로 쪼개져 보이는
// 문제가 있었음. 거래명세서는 이제 항상 1건만 생성되므로(POST /거래명세서요청 참고),
// "번호 1개 = 화면 1줄"이 되도록 되돌림).
export type 레벨1그룹 = {
  key: string; // 거래명세서번호
  거래명세서번호: string;
  사업부: string;
  거래처명: string;
  업무명: string; // 그룹에 등장한 고유 업무명을 ", "로 합친 문자열(담당자와 동일 패턴)
  담당자: string;
  의뢰서건수: number;
  청구페이지: number;
  장수: number;
  봉입건수: number;
  용지수량: number;
  봉투수량: number;
  삽지수량: number;
  // "수정전공급가액" 열 전용(2026-08-23부터 거래명세서번호 단위 값 — 확정공급가액과 동일하게
  // 그룹 내 모든 라인이 항상 같은 값이라 합산하면 안 되고 아무 라인이나 대표로 쓴다. 그룹 내
  // 하나라도 단가 미등록(null)이면 전체 null.
  예상공급가액: number | null;
  발송여부: 0 | 1;
  편집여부: 0 | 1; // 거래명세서번호 단위 값이라 그룹 내 모든 라인이 항상 동일 — 아무 라인이나 사용
  발행가능: 0 | 1; // 편집여부와 동일하게 거래명세서번호 단위 값(2026-08-12)
  수정이력있음: boolean; // "편집됨" 배지 표시 전용(2026-08-13) — 편집여부와 동일하게 그룹 내 동일값
  합계증감: number; // 배지 색상 결정용(2026-08-14) — 편집여부와 동일하게 그룹 내 동일값
  확정공급가액: number; // "청구공급가액" 열 전용(2026-08-14) — 편집여부와 동일하게 그룹 내 동일값
};

export function build레벨1그룹(rows: 발행행[]): 레벨1그룹[] {
  const map = new Map<string, 발행행[]>();
  for (const r of rows) {
    const key = r.거래명세서번호;
    const arr = map.get(key);
    if (arr) arr.push(r);
    else map.set(key, [r]);
  }

  return Array.from(map.entries()).map(([key, lines]) => {
    const 단가미등록있음 = lines.some((l) => l.예상공급가액 === null);
    // 2026-08-23 이전(구버전 응답, `.claude/plans/bug_예상공급가액_부가세미반영.md` 참고)엔
    // 예상공급가액이 의뢰서 개별 몫이라 합산이 맞았지만, 지금은 거래명세서번호 단위 값(확정공급가액과
    // 동일한 값이 모든 라인에 반복)이라 합산하면 의뢰서건수(19건 등)만큼 부풀려진다(사용자 실사용
    // 제보로 발견 — 취소·확정 낙관적 업데이트를 아무리 고쳐도 서버가 준 정확한 반복값을 여기서
    // 다시 더해버려 계속 재현됐음).
    const sum = (f: (r: 발행행) => number) => lines.reduce((s, l) => s + f(l), 0);
    return {
      key,
      거래명세서번호: lines[0].거래명세서번호,
      사업부: lines[0].사업부,
      거래처명: lines[0].거래처명,
      업무명: Array.from(new Set(lines.map((l) => l.업무명))).sort((a, b) => a.localeCompare(b, "ko")).join(", "),
      담당자: Array.from(new Set(lines.map((l) => l.담당자))).sort((a, b) => a.localeCompare(b, "ko")).join(", "),
      의뢰서건수: lines.length,
      청구페이지: sum((l) => l.청구페이지),
      장수: sum((l) => l.장수),
      봉입건수: sum((l) => l.봉입건수),
      용지수량: sum((l) => l.용지수량),
      봉투수량: sum((l) => l.봉투수량),
      삽지수량: sum((l) => l.삽지수량),
      예상공급가액: 단가미등록있음 ? null : lines[0].예상공급가액,
      발송여부: lines[0].발송여부,
      편집여부: lines[0].편집여부,
      발행가능: lines[0].발행가능,
      수정이력있음: lines[0].수정이력있음,
      합계증감: lines[0].합계증감,
      확정공급가액: lines[0].확정공급가액,
    };
  });
}
